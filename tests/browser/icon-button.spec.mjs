import { test, expect } from '@playwright/test';

test('Icon Button uses distinct press and release timings and supports keyboard activation', async ({ page }) => {
  await page.goto('/#component-testing');
  const stage = page.getByRole('region', { name: 'Component preview' });
  const button = stage.getByRole('button', { name: 'Cast', exact: true });
  await expect(page.getByRole('combobox', { name: 'Background', exact: true })).toHaveValue('black');
  await expect(stage).toHaveCSS('background-color', 'rgb(0, 0, 0)');
  await expect(button).toHaveCSS('width', '44px');
  await expect(button).toHaveCSS('height', '44px');
  await expect(button).toHaveCSS('backdrop-filter', 'none');
  await expect(button).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  const icon = button.locator('img');
  await expect(icon).toHaveCSS('width', '24px');
  await expect(icon).toHaveCSS('height', '24px');
  expect(await icon.evaluate(img => img.complete && img.naturalWidth === 24)).toBe(true);
  await button.screenshot({ path: 'test-results/icon-button-default.png' });

  await button.hover();
  await page.mouse.down();
  await expect(button).toHaveCSS('transition-duration', '0.1s');
  await expect(button).toHaveCSS('background-color', 'rgba(255, 255, 255, 0.08)');
  await expect(button).toHaveCSS('backdrop-filter', 'none');
  await button.screenshot({ path: 'test-results/icon-button-pressed.png' });
  await page.mouse.up();
  await expect(button).toHaveCSS('transition-duration', '0.15s');
  await expect(button).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  await button.press('Space');
  await expect(page.getByText('Activations: 2')).toBeVisible();
  await expect(button).toHaveCSS('outline-style', 'solid');
});

test('Component Testing can hold states and pause the background independently', async ({ page }) => {
  await page.goto('/#component-testing');
  const stage = page.getByRole('region', { name: 'Component preview' });
  await page.getByRole('combobox', { name: 'Background', exact: true }).selectOption('pattern');
  const pattern = stage.locator('.testing-pattern');
  const state = page.getByRole('combobox', { name: 'State', exact: true });
  await expect(pattern).toHaveCSS('animation-play-state', 'paused');
  await page.getByRole('button', { name: 'Play background' }).click();
  await expect(pattern).toHaveCSS('animation-play-state', 'running');
  await page.getByRole('combobox', { name: 'Transition speed', exact: true }).selectOption('slow');
  await state.selectOption('pressed');
  const button = stage.getByRole('button', { name: 'Cast', exact: true });
  await expect(button).toHaveCSS('transition-duration', '0.85s');
  await expect(button).toHaveCSS('background-color', 'rgba(255, 255, 255, 0.08)');
  await page.getByRole('button', { name: 'Pause background' }).click();
  await expect(pattern).toHaveCSS('animation-play-state', 'paused');
  await expect(button).toHaveCSS('background-color', 'rgba(255, 255, 255, 0.08)');
  await page.locator('#component-testing').screenshot({ path: 'test-results/component-testing.png' });
  await state.selectOption('disabled');
  await expect(button).toBeDisabled();
  await page.getByRole('navigation', { name: 'Components' }).getByRole('button', { name: 'Button', exact: true }).click();
  await expect(stage.getByRole('button', { name: 'Test action' })).toBeEnabled();
  await state.selectOption('loading');
  await expect(stage.getByRole('button', { name: 'Test action' })).toHaveAttribute('aria-busy', 'true');
  await expect(page.getByRole('heading', { name: 'Usage guidelines' })).toBeVisible();
  await expect(page.locator('pre')).toContainText('Save changes');
  await page.getByRole('navigation', { name: 'Foundations' }).getByRole('button', { name: 'Design tokens' }).click();
  await expect(page.getByText('--mds-color-background-brand', { exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Components' }).getByRole('button', { name: 'Icon Button', exact: true }).click();
  await expect(stage.getByRole('button', { name: 'Cast', exact: true })).toBeEnabled();
  await expect(page.locator('pre')).toContainText('openDevicePicker');
});
